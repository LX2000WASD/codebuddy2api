"""Inject a stable, account-isolated upstream prompt_cache_key.

Ported from the panel gateway (internal/upstream/cache_key.go, reference repo
linguo2625469/workbuddy2api-panel @ 6b31db6). The upstream serves a prefix cache keyed by
this field: measured on the reference implementation, an identical 8k-token prefix cost
~0.34 credits without the key and ~0.02 with it (about a 17x reduction). The gateway
therefore injects one stable key per account and conversation so consecutive requests from
the same client reuse the same upstream prefix.

Hard constraint -- the isolation segment must be per credential. Reusing one cache key
across accounts makes the upstream serve one account's cached prefix to another, which
leaks conversation content. The panel used the raw account UID for this; we use
app.client_profiles.account_key, which already hashes [profile, uid, enterpriseId], so a
bare uid is never used and two accounts (or the same uid on two domains) cannot collide.

Injection priority, matching the panel:

1. the client already sent a non-empty prompt_cache_key -> keep it verbatim;
2. the body carries conversation_id / conversationId -> use it as the session source;
3. otherwise the resolved session key (explicit header, metadata, fingerprint or the
   legacy system+first-user derivation) -> use it;
4. nothing at all -> a constant session segment. The key still carries the isolation
   segment, so cross-account collisions remain impossible; an empty session simply does
   not reuse a prefix.

Priority 3 is the panel fix 20254d8: without it, traffic with no conversation id
(Anthropic / Claude Code) collapses to one constant key per account, so every client on
that account shares a single constantly-evicted prefix slot.
"""

from __future__ import annotations

import hashlib

# Prefix marks the key as generated by this gateway. The panel used "wb2a-"; we use our
# own so keys minted by the two implementations are never confused in upstream logs.
KEY_PREFIX = "pcb2a-"
# Length of the isolation segment in characters (panel used the first 8 of the uid).
ISOLATION_LENGTH = 8
# Session segment length: 16 bytes of sha256, hex encoded (panel identical).
SESSION_DIGEST_BYTES = 16
# Session segment used when no session source exists at all.
NO_SESSION = "-"


def isolation_factor(profile: str, account_key_value: str) -> str:
    """Return the prompt-cache isolation segment for one credential.

    **This is the single place that decides the upstream cache bucket scope.** Replace this
    function to change it; nothing else needs to move.

    Chosen today: bucket per (account, product/region), i.e. profile + account_key.

    Rationale:

    * account_key (app/client_profiles.py:71) hashes [profile, uid, enterpriseId], so the raw
      uid is never used (hard requirement) and two credentials can never collide;
    * folding profile in again is redundant for hashing but keeps the choice explicit, and
      the same uid on the domestic and international domains is genuinely two independent
      upstreams with independent billing -- sharing one prefix slot would only evict each
      other, which is exactly the 20254d8 failure mode;
    * the opposite risk (splitting a bucket that could have been shared) only costs hit
      rate; it never produces a wrong answer.

    .. warning::
       **The upstream bucket scope is NOT verified.** The reference implementation is
       single-domain and never exercises two products on one uid, so whether the upstream
       keys its prefix cache per account or per (account, product) cannot be inferred from
       it. This choice is reasoned, not measured. See the report, section 5.3.
    """
    return hashlib.sha256(f"{profile}|{account_key_value}".encode("utf-8")).hexdigest()


def session_source(payload, context, session_key_value):
    """Resolve the session segment source, mirroring the panel priority order."""
    if isinstance(payload, dict):
        metadata = payload.get("metadata")
        for field in ("conversation_id", "conversationId"):
            for source in (payload, metadata):
                if not isinstance(source, dict):
                    continue
                value = source.get(field)
                if isinstance(value, str) and value.strip():
                    return value.strip()
    if context is not None and getattr(context, "scoped", False):
        value = getattr(context, "session_key", None)
        if isinstance(value, str) and value:
            return value
    if isinstance(session_key_value, str) and session_key_value:
        return session_key_value
    return ""


def build_cache_key(profile, account_key_value, session):
    """Build pcb2a-<isolation8>-<sessionHex> for one credential and session."""
    isolation = isolation_factor(profile, account_key_value)
    source = session if isinstance(session, str) and session else NO_SESSION
    digest = hashlib.sha256(f"{isolation}|{source}".encode("utf-8")).hexdigest()
    return KEY_PREFIX + isolation[:ISOLATION_LENGTH] + "-" + digest[:SESSION_DIGEST_BYTES * 2]


def inject_prompt_cache_key(body, profile, account_key_value, session):
    """Return body with a generated prompt_cache_key, or unchanged when not applicable.

    An explicit non-empty client key always wins and is never overwritten. Callers are
    expected to have already checked the prompt_cache_key_enabled switch; this function
    only decides whether a key is *available* to generate.
    """
    if not isinstance(body, dict):
        return body
    existing = body.get("prompt_cache_key")
    if isinstance(existing, str) and existing:
        return body
    if not profile or not account_key_value:
        return body
    return {**body, "prompt_cache_key": build_cache_key(profile, account_key_value, session)}
